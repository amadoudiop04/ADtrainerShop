@Injectable({ providedIn: 'root' })
export class TranslationService {
  private _lang = signal<Lang>('FR');
  readonly lang = this._lang.asReadonly();

  constructor(@Inject(PLATFORM_ID) private platformId: Object) {
    if (isPlatformBrowser(this.platformId)) {
      const saved = localStorage.getItem('adtrainer_language') as Lang | null;
      if (saved === 'EN' || saved === 'FR') this._lang.set(saved);
    }
  }

  setLang(lang: Lang): void {
    this._lang.set(lang);
    if (isPlatformBrowser(this.platformId)) {
      localStorage.setItem('adtrainer_language', lang);
    }
  }

  toggle(): void {
    this.setLang(this._lang() === 'FR' ? 'EN' : 'FR');
  }

  t(key: string): string {
    return TRANSLATIONS[this._lang()][key] ?? TRANSLATIONS['FR'][key] ?? key;
  }
}
